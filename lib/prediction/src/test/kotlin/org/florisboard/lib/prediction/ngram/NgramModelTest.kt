package org.florisboard.lib.prediction.ngram

import io.kotest.assertions.withClue
import io.kotest.core.spec.style.FunSpec
import io.kotest.matchers.shouldBe
import io.kotest.matchers.ints.shouldBeGreaterThan
import java.io.File
import java.io.RandomAccessFile
import java.nio.ByteBuffer
import java.nio.channels.FileChannel
import java.util.concurrent.Executors
import java.util.concurrent.TimeUnit

/**
 * Checks the Kotlin reader against the Python reference reader (tools/lm/lmtool/binfmt.py). The fixtures and the
 * expected results are generated by tools/lm/make_fixture.py.
 */
class NgramModelTest : FunSpec({
    fun resource(name: String) = checkNotNull(NgramModelTest::class.java.getResourceAsStream("/ngram/$name")) {
        "missing test resource ngram/$name (run tools/lm/make_fixture.py)"
    }

    fun parseFloat(s: String): Float = when (s) {
        "-inf" -> Float.NEGATIVE_INFINITY
        "inf" -> Float.POSITIVE_INFINITY
        else -> s.toFloat()
    }

    fun parseCandidates(s: String): List<NgramCandidate> =
        if (s.isEmpty()) emptyList() else s.split(';').map {
            val (id, lp) = it.split(':')
            NgramCandidate(id.toInt(), parseFloat(lp))
        }

    for (fixture in listOf("tiny3", "tiny4")) {
        val model = resource("$fixture.bin").use { NgramModel.load(it) }
        val expected = resource("$fixture.expected.tsv").bufferedReader(Charsets.UTF_8).readLines()
            .filter { it.isNotEmpty() }
            .map { it.split('\t') }

        test("$fixture: header and vocabulary match the Python reference") {
            val v = expected.first { it[0] == "V" }[1].toInt()
            model.vocabularySize shouldBe v
            model.language shouldBe "en"
            model.formatVersion shouldBe 2
            var words = 0
            for (row in expected.filter { it[0] == "W" }) {
                val id = row[1].toInt()
                withClue("word id $id") {
                    model.word(id) shouldBe row[2]
                    model.casedForm(id) shouldBe row[3]
                    model.isCapitalized(id) shouldBe (row[4] == "1")
                    model.unigramLogProb(id) shouldBe parseFloat(row[5])
                    model.isValid(id) shouldBe (row[6] == "1")
                    model.isListed(id) shouldBe (row[7] == "1")
                }
                words++
            }
            words shouldBe v
        }

        test("$fixture: wordId lookups match") {
            for (row in expected.filter { it[0] == "I" }) {
                withClue("wordId(${row[1]})") { model.wordId(row[1]) shouldBe row[2].toInt() }
            }
        }

        test("$fixture: logProb with backoff matches") {
            var n = 0
            for (row in expected.filter { it[0] == "L" }) {
                val w = row[1].toInt()
                val p1 = row[2].toInt()
                val p2 = row[3].toInt()
                withClue("logProb($w | $p2 $p1)") { model.logProb(w, p1, p2) shouldBe parseFloat(row[4]) }
                n++
            }
            n shouldBeGreaterThan 1000
        }

        test("$fixture: topNext matches") {
            for (row in expected.filter { it[0] == "N" }) {
                val p1 = row[1].toInt()
                val p2 = row[2].toInt()
                val limit = row[3].toInt()
                withClue("topNext($p2 $p1, $limit)") {
                    model.topNext(p1, p2, limit) shouldBe parseCandidates(row.getOrElse(4) { "" })
                }
            }
        }

        test("$fixture: prefixRange and topCompletions match") {
            for (row in expected.filter { it[0] == "R" }) {
                val range = model.prefixRange(row[1])
                withClue("prefixRange('${row[1]}')") {
                    range.first shouldBe row[2].toInt()
                    (range.last + 1) shouldBe maxOf(row[3].toInt(), row[2].toInt())
                }
            }
            for (row in expected.filter { it[0] == "C" }) {
                val prefix = row[1]
                val p1 = row[2].toInt()
                val p2 = row[3].toInt()
                val limit = row[4].toInt()
                withClue("topCompletions('$prefix', $p2 $p1, $limit)") {
                    model.topCompletions(prefix, p1, p2, limit) shouldBe parseCandidates(row.getOrElse(5) { "" })
                }
            }
        }
    }

    test("folded prefixes ignore diacritics, apostrophes and case") {
        val model = resource("tiny3.bin").use { NgramModel.load(it) }
        val een = model.wordId("één")
        (een in model.prefixRange("een")) shouldBe true
        (model.wordId("don't") in model.prefixRange("dont")) shouldBe true
        (model.wordId("amsterdam") in model.prefixRange("AMS")) shouldBe true
        model.topCompletions("dont", NgramModel.BOS_ID, limit = 3).map { model.word(it.wordId) } shouldBe listOf("don't")
        model.casedForm(model.wordId("iphone")) shouldBe "iPhone"
        model.casedForm(model.wordId("fbi")) shouldBe "FBI"
        model.casedForm(model.wordId("i")) shouldBe "I"
        model.wordId("Amsterdam") shouldBe NgramModel.UNKNOWN_ID
        model.wordId(NgramModel.normalizeToken("Amsterdam")) shouldBe model.wordId("amsterdam")
        model.wordId(NgramModel.normalizeToken("Don’t")) shouldBe model.wordId("don't")
    }

    test("validity: listed, capitalised and frequent words are valid, other words and <s> are not") {
        val model = resource("tiny3.bin").use { NgramModel.load(it) }
        model.isValid(NgramModel.BOS_ID) shouldBe false
        model.isValid(NgramModel.UNKNOWN_ID) shouldBe false
        model.isValid(model.vocabularySize) shouldBe false
        model.isValid(model.wordId("know")) shouldBe true
        model.isValid(model.wordId("amsterdam")) shouldBe true // capitalised
        model.isValid(model.wordId("nasa")) shouldBe true // capitalised
        model.isListed(model.wordId("know")) shouldBe true
        model.isListed(model.wordId("nasa")) shouldBe false // valid through its capitals only
        model.isListed(NgramModel.BOS_ID) shouldBe false
        for (id in 1 until model.vocabularySize) if (model.isListed(id)) model.isValid(id) shouldBe true
        // Not in the fixture word list and below the frequency threshold (tools/lm/make_fixture.py).
        for (w in listOf("straks", "gewoon", "echt", "zeer")) withClue(w) { model.isValid(model.wordId(w)) shouldBe false }
        model.validCount shouldBe (1 until model.vocabularySize).count { model.isValid(it) }
        (model.validCount < model.vocabularySize - 1) shouldBe true
    }

    test("version 1 files load, every word is valid, none is listed and the n-grams equal the version 2 file") {
        val v2 = resource("tiny3.bin").use { NgramModel.load(it) }
        val v1 = resource("tiny3v1.bin").use { NgramModel.load(it) }
        v1.formatVersion shouldBe 1
        v1.vocabularySize shouldBe v2.vocabularySize
        v1.validCount shouldBe v1.vocabularySize - 1
        v1.isValid(NgramModel.BOS_ID) shouldBe false
        for (id in 1 until v1.vocabularySize) {
            v1.isValid(id) shouldBe true
            v1.isListed(id) shouldBe false
            v1.word(id) shouldBe v2.word(id)
            v1.casedForm(id) shouldBe v2.casedForm(id)
            v1.unigramLogProb(id) shouldBe v2.unigramLogProb(id)
            v1.topNext(id, NgramModel.BOS_ID, 5) shouldBe v2.topNext(id, NgramModel.BOS_ID, 5)
            v1.logProb(id, v1.wordId("i"), NgramModel.BOS_ID) shouldBe v2.logProb(id, v2.wordId("i"), NgramModel.BOS_ID)
        }
        v1.topCompletions("d", v1.wordId("i"), NgramModel.BOS_ID, 5) shouldBe v2.topCompletions("d", v2.wordId("i"), NgramModel.BOS_ID, 5)
        (v1.memoryBytes < v2.memoryBytes) shouldBe true
    }

    test("rejects a version 2 file without its validity section and unknown versions") {
        val bytes = resource("tiny3.bin").use { it.readBytes() }
        val buf = ByteBuffer.wrap(bytes).order(java.nio.ByteOrder.LITTLE_ENDIAN)
        val sections = buf.getShort(6).toInt()
        val noVald = bytes.copyOf()
        for (i in 0 until sections) {
            val at = 32 + 12 * i
            if (String(noVald, at, 4, Charsets.US_ASCII) == "VALD") "XXXX".toByteArray().copyInto(noVald, at)
        }
        runCatching { NgramModel.load(ByteBuffer.wrap(noVald)) }.exceptionOrNull()?.message shouldBe "missing section VALD"
        val v3 = bytes.copyOf()
        v3[4] = 3
        runCatching { NgramModel.load(ByteBuffer.wrap(v3)) }.exceptionOrNull()?.message shouldBe "unsupported n-gram model version 3"
        // A VALD section whose length is not two bit sets of the vocabulary.
        val shortVald = bytes.copyOf()
        val table = ByteBuffer.wrap(shortVald).order(java.nio.ByteOrder.LITTLE_ENDIAN)
        for (i in 0 until sections) {
            val at = 32 + 12 * i
            if (String(shortVald, at, 4, Charsets.US_ASCII) == "VALD") table.putInt(at + 8, table.getInt(at + 8) - 1)
        }
        runCatching { NgramModel.load(ByteBuffer.wrap(shortVald)) }.exceptionOrNull()?.message shouldBe "bad VALD size"
    }

    test("contextOf applies the training tokenisation") {
        val model = resource("tiny3.bin").use { NgramModel.load(it) }
        val i = model.wordId("i")
        val dont = model.wordId("don't")
        val know = model.wordId("know")
        model.contextOf("") shouldBe NgramContext(NgramModel.BOS_ID, NgramModel.UNKNOWN_ID)
        model.contextOf("Hello there. ") shouldBe NgramContext(NgramModel.BOS_ID, NgramModel.UNKNOWN_ID)
        model.contextOf("Really?! ") shouldBe NgramContext(NgramModel.BOS_ID, NgramModel.UNKNOWN_ID)
        model.contextOf("I ") shouldBe NgramContext(i, NgramModel.BOS_ID)
        model.contextOf("Ok. I don’t ") shouldBe NgramContext(dont, i)
        model.contextOf("I don't 42 know ") shouldBe NgramContext(know, dont)
        model.contextOf("I don't know... ") shouldBe NgramContext(know, dont)
        model.contextOf("I, don't ") shouldBe NgramContext(dont, i)
        model.contextOf("qwertyuiop ") shouldBe NgramContext(NgramModel.UNKNOWN_ID, NgramModel.BOS_ID)
    }

    test("loads from a ByteBuffer and answers concurrently") {
        val bytes = resource("tiny3.bin").use { it.readBytes() }
        val model = NgramModel.load(ByteBuffer.wrap(bytes))
        val reference = (0 until model.vocabularySize).map { model.topNext(it, NgramModel.BOS_ID, 5) }
        val pool = Executors.newFixedThreadPool(8)
        val futures = (0 until 64).map { t ->
            pool.submit<Boolean> {
                (0 until model.vocabularySize).all { id ->
                    model.topNext(id, NgramModel.BOS_ID, 5) == reference[id] &&
                        model.topCompletions(model.word(maxOf(id, 1)).take(1), id, (id * 7 + t) % model.vocabularySize, 4)
                            .isNotEmpty()
                }
            }
        }
        futures.all { it.get() } shouldBe true
        pool.shutdown()
        pool.awaitTermination(10, TimeUnit.SECONDS) shouldBe true
    }

    test("a direct buffer that starts after position 0 and a mapping at a file offset answer like the heap copy, concurrently") {
        for (fixture in listOf("tiny3", "tiny4")) {
            val bytes = resource("$fixture.bin").use { it.readBytes() }
            val heap = NgramModel.load(ByteBuffer.wrap(bytes))
            // Direct, with 13 bytes before the file and 5 after it; the position marks the start of the file.
            val direct = ByteBuffer.allocateDirect(13 + bytes.size + 5)
            direct.put(ByteArray(13) { 0x5A }).put(bytes).put(ByteArray(5) { 0x5A }).flip()
            direct.position(13)
            val fromDirect = NgramModel.load(direct)
            direct.position() shouldBe 13
            direct.limit() shouldBe 13 + bytes.size + 5
            // Mapped at an offset inside a larger file, like an uncompressed asset inside the APK.
            val file = File.createTempFile(fixture, ".apk").apply { deleteOnExit() }
            file.writeBytes(ByteArray(13) { 0x5A } + bytes + ByteArray(5) { 0x5A })
            val mapped = RandomAccessFile(file, "r").use { it.channel.map(FileChannel.MapMode.READ_ONLY, 13, bytes.size.toLong()) }
            val fromMapping = NgramModel.load(mapped)
            fromDirect.isDirect shouldBe true
            fromMapping.isDirect shouldBe true

            val v = heap.vocabularySize
            fun answers(m: NgramModel, salt: Int): List<Any> = (0 until v).flatMap { id ->
                val prev2 = (id * 7 + salt) % v
                listOf(
                    m.word(id), m.isValid(id), m.isListed(id), m.casedForm(id), m.unigramLogProb(id),
                    m.wordId(m.word(id)), m.topNext(id, NgramModel.BOS_ID, 5), m.topNext(id, prev2, 3),
                    m.topCompletions(m.word(maxOf(id, 1)).take(1), id, prev2, 4),
                ) + (0 until v).map { w -> m.logProb(w, id, prev2) }
            }
            val reference = (0 until 4).map { salt -> answers(heap, salt) }
            val pool = Executors.newFixedThreadPool(8)
            val futures = (0 until 32).map { t ->
                pool.submit<Boolean> {
                    val m = if (t % 2 == 0) fromDirect else fromMapping
                    answers(m, t % 4) == reference[t % 4]
                }
            }
            withClue(fixture) { futures.all { it.get() } shouldBe true }
            pool.shutdown()
            pool.awaitTermination(10, TimeUnit.SECONDS) shouldBe true
        }
    }

    test("logProb answers a repeated context from its hashed lists with exactly the scanned values") {
        val model = resource("tiny3.bin").use { NgramModel.load(it) }
        val v = model.vocabularySize
        val contexts = (0 until v).flatMap { p1 -> listOf(p1 to NgramModel.BOS_ID, p1 to NgramModel.UNKNOWN_ID, p1 to (p1 * 7) % v) } +
            listOf(NgramModel.UNKNOWN_ID to NgramModel.UNKNOWN_ID)
        for ((p1, p2) in contexts) {
            // Alternating with another context forces a scan on every call; repeating the context hashes its lists.
            val scanned = (0..v).map { w ->
                model.logProb(1, NgramModel.UNKNOWN_ID, NgramModel.UNKNOWN_ID)
                model.logProb(w, p1, p2)
            }
            val repeated = (0..v).map { w -> model.logProb(w, p1, p2) }
            withClue("context ($p2, $p1)") { repeated shouldBe scanned }
        }
    }

    test("a stream load larger than its heap budget fails after the header, before the copy") {
        val bytes = resource("tiny3.bin").use { it.readBytes() }
        NgramModel.load(bytes.inputStream(), maxBytes = bytes.size.toLong()).vocabularySize shouldBeGreaterThan 0
        val input = bytes.inputStream()
        val result = runCatching { NgramModel.load(input, maxBytes = bytes.size - 1L) }
        (result.exceptionOrNull() is IllegalStateException) shouldBe true
        // Only the 32-byte header was read.
        input.available() shouldBe bytes.size - 32
    }

    test("rejects files that are not n-gram models") {
        val result = runCatching { NgramModel.load(ByteBuffer.wrap(ByteArray(64))) }
        result.isFailure shouldBe true
    }
})
